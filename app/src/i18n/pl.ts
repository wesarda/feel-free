/** Polish plural forms: 1 stopień, 2–4 stopnie, 5+ stopni (but 12–14 stopni). */
export function plural(n: number, one: string, few: string, many: string): string {
  const n10 = n % 10
  const n100 = n % 100
  const word = n === 1 ? one : n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14) ? few : many
  return `${n} ${word}`
}
